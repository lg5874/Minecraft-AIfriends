/** 判断一句话是不是"念日志" */
function isMachineTalk (text) {
  const t = String(text || '')
  if (!t) return false
  // 整句几乎全是英文 -> 机器味
  const letters = t.replace(/[^a-zA-Z_]/g, '')
  if (letters.length > 4 && letters.length > t.length * 0.6) return true
  return MACHINE_TALK.some(re => re.test(t))
}

/**
 * 从 stateLine 里读"现在有多危险"，决定这一句该说多长。
 *
 * 【为什么要有这个 · 2026-11-13】用户把服务器改成普通模式（有怪）并把 bot 传送到地面。
 * 真人被追的时候只说两三个字（"后面""跑""血"），绝不会说
 * "这僵尸怎么这么多啊"这种完整句。长度不塌缩，一眼就不是人。
 *
 * stateLine 由 perceive.brief() 拼出来，形如：
 *   "地面开阔；威胁：两只僵尸在10格外；人：Xylitol6983；血 4/20，饿 12/20，手上是石剑"
 * 血量和威胁都在里面，所以这里能直接判。
 *
 * @returns {{level:'critical'|'hurt'|'ok', hp:number|null, why:string}}
 */
function dangerOf (text) {
  const t = String(text || '')
  const m = t.match(/血\s*(\d+)\s*\/\s*20/)
  const hp = m ? Number(m[1]) : null
  const threatLine = (t.match(/威胁：([^；;\n]*)/) || [])[1] || ''
  const imminent = /被追|正在被|追着|着火|岩浆|在水里|快淹|掉血/.test(t) ||
    /僵尸|苦力怕|骷髅|蜘蛛|女巫|卫道士|劫掠|末影|猪灵|疣猪/.test(threatLine)
  if (hp != null && hp <= 6) return { level: 'critical', hp, why: '血不多了' }
  if (imminent) return { level: 'critical', hp, why: '附近有东西' }
  if (hp != null && hp <= 14) return { level: 'hurt', hp, why: '身上带伤' }
  return { level: 'ok', hp, why: '' }
}

/**
 * 元信息泄漏的结构化判据（2026-11-13）。
 *
 * 【为什么不用枚举词】四条正则挡得住已知的那种独白，挡不住换一种说法。
 * 这里数的是**信号类别**：一句话里同时出现两类以上"元信息"，
 * 它就是在跟提示词说话，不是在跟人说话。
 *
 * 实测样本（154 字，危险态测试里吐的）：
 *   "…这一句最多三个字…不能报数字…但如果这次提示说50字？…保守起见"
 * 命中：字数 + 数值约束 + 规则引用 + 自指 = 4 类。
 *
 * @returns {string[]} 命中的信号类别
 */
function metaSignals (text) {
  const t = String(text || '')
  if (!t) return []
  const hits = []
  if (/[一二两三四五六七八九十几\d]\s*个?字/.test(t)) hits.push('字数')
  if (/最多|不超过|不能超过|上限|至少/.test(t) && /\d|[一二两三四五六七八九十]/.test(t)) hits.push('数值约束')
  if (/规矩|提示|规则|设定|要求|限制|死规矩/.test(t)) hits.push('规则引用')
  if (/血\s*\d|威胁|状态栏|心情值|好感度/.test(t)) hits.push('状态变量')
  if (/这一句|这次|刚才那句|保守起见|我应该|我该说/.test(t)) hits.push('自指')
  // 第六类：在讨论"这句话该怎么写"（指令式元语言）
  // 实测现场：`喊一句 XJJ_SPAM1 等等，带名字` —— "带名字"是提示词口径，不是人话
  if (/带名字|带上名字|点名|要不要说|该不该说|还是不说|得再补一句|换个说法|措辞/.test(t)) hits.push('元语言')
  return hits
}

/**
 * 思考泄漏判定。
 *   命中 ≥2 类元信息 → 泄漏
 *   命中 1 类但是「元语言」→ 也算泄漏
 *     （"带名字""换个说法"这种话，人在游戏里不会对别人说，只会对自己说）
 */
function isMetaLeak (text) {
  const hits = metaSignals(text)
  if (hits.length >= 2) return true
  if (hits.includes('元语言')) return true
  return false
}

function isLeak (text) {
  if (!text) return false
  return LEAK.some(re => re.test(text))
}

