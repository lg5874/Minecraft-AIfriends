/** 聊天时的额外要求 */
function chatHint (opts) {
  const maxLen = (opts && opts.maxLen) || 60
  const lastSaid = (opts && opts.lastSaid) || ''
  const lastBlock = lastSaid
    ? `\n- 你上一句说的是：「${lastSaid}」。这一句不许跟它重复，开头也不许一样。`
    : ''
  return `现在你要回一句话。要求：
- 只说你要打出来的字，不要加引号、不要加"我说："这种前缀
- 不超过 ${maxLen} 个字
- 像真人打字，可以有语气词
- 不数次数，不报具体数字（剩几块、差几格这种都不说）
- 不汇报自己在干嘛，除非对方问${lastBlock}
- 如果对方说的东西你不想接，可以直接换话题或者敷衍一句
- 如果这情况你根本不想理，就输出 [不理]`
}

